import { readFileSync } from 'fs';
const env = readFileSync('.env', 'utf8');
process.env.DATABASE_URL = env.match(/DATABASE_URL="([^"]+)"/)[1];
const { PrismaClient } = await import('@prisma/client');
const p = new PrismaClient();
const withPass = await p.user.findMany({ where: { passwordHash: { not: null } }, select: { phone: true, userName: true, firstName: true, lastName: true, isActive: true, cityId: true, provinceId: true }, take: 5 });
console.log('== Users with password:', withPass.length);
withPass.forEach(u => console.log(JSON.stringify(u)));
const total = await p.user.count();
const noName = await p.user.count({ where: { OR: [{ firstName: '' }] } });
console.log('== total users:', total, '| empty firstName:', noName);
const prodCount = await p.product.count();
const prodConfirmed = await p.product.count({ where: { status: 'confirmed' } });
const prodPending = await p.product.count({ where: { status: 'pending' } });
console.log('== products:', prodCount, '| confirmed:', prodConfirmed, '| pending:', prodPending);
const brCount = await p.buyRequest.count();
console.log('== buyRequests:', brCount);
const sample = await p.product.findFirst({ where: { status: 'confirmed' }, select: { id: true, userId: true, productName: true } });
console.log('== sample product:', JSON.stringify(sample));
await p.$disconnect();

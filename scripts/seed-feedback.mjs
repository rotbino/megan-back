async function main() {
  // نویسنده بذرها: یک کاربر ادمین (مالک) — در فید با بج «تیم ایمچ» نمایش داده می‌شود
  const admin = await p.user.findFirst({
    where: { role: 'ADMIN' },
    select: { id: true, firstName: true, lastName: true },
  });
  if (!admin) {
    console.error('✖ هیچ ادمینی پیدا نشد — اول npm run make-admin');
    process.exit(1);
  }
  console.log(`✔ نویسنده بذر: ${admin.firstName} ${admin.lastName} (${admin.id})`);

  const existing = await p.feedbackItem.count({ where: { isStaff: true } });
  if (existing > 0) {
    console.log(`↷ ${existing} بازخورد تیم از قبل موجود است — بذر تکراری وارد نشد.`);
    return;
  }

  for (const f of STAFF_FEEDBACK) {
    await p.feedbackItem.create({
      data: {
        userId: admin.id,
        category: f.category,
        body: f.body,
        isStaff: true,
        createdAt: new Date(Date.now() - f.daysAgo * 86_400_000 - 3_600_000),
      },
    });
  }
  console.log(`✔ ${STAFF_FEEDBACK.length} بازخورد نمونه تیم ایمچ ثبت شد.`);
}

main().finally(() => p.$disconnect());

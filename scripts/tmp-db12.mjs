import { readFileSync } from 'fs';
const env = readFileSync('.env', 'utf8');
process.env.DATABASE_URL = env.match(/DATABASE_URL="([^"]+)"/)[1];
const { PrismaClient } = await import('@prisma/client');
const p = new PrismaClient();
const del = await p.product.findMany({ where: { status: 'deleted' }, select: { id: true, productName: true, createdAt: true, updatedAt: true }, take: 5, orderBy: { updatedAt: 'desc' } });
del.forEach(d => console.log(JSON.stringify({ id: d.id, name: d.productName?.slice(0, 30), created: d.createdAt?.toISOString?.()?.slice(0, 16), updated: d.updatedAt?.toISOString?.()?.slice(0, 16) })));
const confirmed = await p.product.findMany({ where: { status: 'confirmed' }, select: { id: true, productName: true, createdAt: true }, take: 3, orderBy: { updatedAt: 'desc' } });
confirmed.forEach(c => console.log('CONFIRMED:', JSON.stringify({ id: c.id, name: c.productName?.slice(0, 30), created: c.createdAt?.toISOString?.()?.slice(0, 16) })));
await p.$disconnect();

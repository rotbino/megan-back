// تست واحد منطق «متن خودکار باسکول/اینکوباک» + «جایگزینی برند» — بدون دیتابیس.
// عین توابع سرویس (importer.service.ts) اینجا تکرار شده؛ اگر سرویس عوض شد
// این تست هم هم‌زمان آپدیت شود.
// اجرا: node scripts/test-auto-desc.mjs
let pass = 0;
let fail = 0;
const check = (name, cond) => {
  if (cond) { pass++; console.log(`  ✅ ${name}`); }
  else { fail++; console.log(`  ❌ ${name}`); }
};

// ── عین سرویس ──
const normalizeFa = (t) =>
  String(t ?? '')
    .replace(/\u200c/g, ' ')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/\s+/g, ' ')
    .trim();

function isBuskoolAutoDesc(desc) {
  if (!desc) return false;
  const t = normalizeFa(desc);
  const contact = t.includes('برای ارتباط با من رو') && t.includes('به اشتراک بگذارید');
  const brand =
    /در حال خرید و فروش عمده در بازار بزرگ (باسکول|اینکوباک)/.test(t) ||
    /در سامانه ?ی? ?(باسکول|اینکوباک) هستم/.test(t) ||
    /در (وب ?سایت|سایت) (باسکول|اینکوباک)/.test(t);
  return contact && brand;
}

const aimchify = (t) =>
  String(t ?? '')
    .replace(/باس[كک]ول/g, 'آیمچ')
    .replace(/این[كک]وبا[كک]/g, 'آیمچ');

console.log('— متن خودکار (باید همه رد شوند) —');
check(
  'قالب اینکوباک (واقعی در دامپ)',
  isBuskoolAutoDesc(
    'من فروشنده محصولات کشاورزی در سامانه ی اینکوباک هستم. برای ارتباط با من رو دکمه ی ارسال پیام کلیک کنید. خوشحال می شوم اگر پروفایل من را با دوستان خود به اشتراک بگذارید.',
  ),
);
check(
  'قالب باسکول همان الگو',
  isBuskoolAutoDesc(
    'من فروشنده محصولات کشاورزی در سامانه ی باسکول هستم. برای ارتباط با من رو دکمه ی ارسال پیام کلیک کنید. خوشحال می شوم اگر پروفایل من را با دوستان خود به اشتراک بگذارید.',
  ),
);
check(
  'قالب باسکول نسل اول (نمونهٔ مالک)',
  isBuskoolAutoDesc(
    'بشیر قربانی هستم از شهر مریوان در حال خرید و فروش عمده در بازار بزرگ باسکول. برای ارتباط با من روی دکمه ی ارسال پیام بزنید. خوشحال می شوم پروفایل من را با همکارانتان به اشتراک بگذارید.',
  ),
);
check(
  'قالب اینکوباک با نیم‌فاصله (سامانه‌ی) و ک عربی',
  isBuskoolAutoDesc(
    'من خریدار خشكبار در سامانه\u200cی اینكوباك هستم. برای ارتباط با من روی دکمه ی ارسال پیام کلیک کنید. خوشحال می شوم اگر پروفایل من را با دوستان خود به اشتراك بگذارید.',
  ),
);
check(
  'قالب با نوع فعالیت دیگر (ساختمانی)',
  isBuskoolAutoDesc(
    'من فروشنده وسایل ساختمانی در سامانه ی اینکوباک هستم. برای ارتباط با من رو دکمه ی ارسال پیام کلیک کنید. خوشحال می شوم اگر پروفایل من را با دوستان خود به اشتراک بگذارید.',
  ),
);

console.log('— متن واقعی (نباید خودکار تشخیص داده شود) —');
check('متن واقعی بدون برند', !isBuskoolAutoDesc('محدثه نجفیان زاده هستم تاجر بادام درختی تأمین کننده ی تخصصی و مستقیم بادام درختی از قطب.'));
check('متن واقعی با اشاره به باسکول ولی بدون قالب', !isBuskoolAutoDesc('سال هاست در بازار باسکول فعالیت دارم و اکنون محصولاتم را اینجا هم عرضه می‌کنم؛ کیفیت تضمینی.'));
check('متن خالی', !isBuskoolAutoDesc(''));
check('null', !isBuskoolAutoDesc(null));

console.log('— جایگزینی برند —');
check('باسکول → آیمچ', aimchify('در بازار باسکول فعال بودم.') === 'در بازار آیمچ فعال بودم.');
check('اینکوباک → آیمچ', aimchify('عضو قدیمی سایت اینکوباک هستم.') === 'عضو قدیمی سایت آیمچ هستم.');
check('ك عربی', aimchify('در باسكول ثبت‌نام کردم') === 'در آیمچ ثبت‌نام کردم');
check('چند بار + هر دو برند', aimchify('از اینکوباک به باسکول و حالا اینجا آمدم') === 'از آیمچ به آیمچ و حالا اینجا آمدم');
check('بدون برند دست نمی‌خورد', aimchify('فروش عمده پسته اکبری') === 'فروش عمده پسته اکبری');
check('متن خالی', aimchify('') === '');

console.log(`\n${pass} پاس / ${fail} خطا`);
process.exit(fail ? 1 : 0);

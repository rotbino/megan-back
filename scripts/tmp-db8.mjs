import { readFileSync } from 'fs';
const env = readFileSync('.env', 'utf8');
process.env.DATABASE_URL = env.match(/DATABASE_URL="([^"]+)"/)[1];
const { PrismaClient } = await import('@prisma/client');
const p = new PrismaClient();
const dist = await p.buyRequest.groupBy({ by: ['status'], _count: { _all: true } });
console.log('buyRequest status distribution:', JSON.stringify(dist));
const u = await p.user.findFirst({ where: { buyRequests: { some: { status: 'confirmed' } } }, select: { phone: true, id: true } });
console.log('owner of confirmed buyRequest:', JSON.stringify(u));
await p.$disconnect();

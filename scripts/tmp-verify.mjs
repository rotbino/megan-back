import { readFileSync } from 'fs';
const env = readFileSync('.env', 'utf8');
process.env.DATABASE_URL = env.match(/DATABASE_URL="([^"]+)"/)[1];
const { PrismaClient } = await import('@prisma/client');
const p = new PrismaClient();
const noName = await p.user.count({ where: { firstName: '' } });
const noProv = await p.user.count({ where: { OR: [{ provinceId: null }, { provinceId: 0 }] } });
console.log('empty firstName:', noName, '| no province:', noProv);
const samples = await p.user.findMany({ where: { firstName: { not: '' } }, select: { phone: true, firstName: true, lastName: true, provinceId: true, cityId: true }, take: 5 });
samples.forEach(s => console.log(JSON.stringify(s)));
await p.$disconnect();
